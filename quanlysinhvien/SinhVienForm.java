    // Kiem tra ket noi co mo duoc khong
    private Connection layKetNoi() throws Exception {
        Connection conn = DBConnection.getConnection();
        if (conn == null) {
            throw new Exception("Khong ket noi duoc SQL Server. Hay kiem tra DBConnection.");
        }
        return conn;
    }

    // Hien thi danh sach sinh vien len JTable
    private void loadSinhVien() {
        DefaultTableModel model = (DefaultTableModel) tblSinhVien.getModel();
        model.setRowCount(0);

        String sql = "SELECT MaSV, HoTen, NgaySinh, GioiTinh, DiaChi, SoDienThoai "
                   + "FROM SinhVien ORDER BY MaSV";

        try (Connection conn = layKetNoi();
             PreparedStatement ps = conn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("MaSV"),
                    rs.getString("HoTen"),
                    rs.getDate("NgaySinh"),
                    rs.getString("GioiTinh"),
                    rs.getString("DiaChi"),
                    rs.getString("SoDienThoai")
                });
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Khong tai duoc danh sach sinh vien: " + e.getMessage());
        }
    }

    // Lay thong tin tu cac o nhap
    private boolean kiemTraDuLieu() {
        if (jTextField1.getText().trim().isEmpty()
                || jTextField2.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ma sinh vien va Ho ten khong duoc de trong!");
            return false;
        }

        String ngaySinh = jTextField3.getText().trim();
        if (!ngaySinh.isEmpty()) {
            try {
                java.sql.Date.valueOf(ngaySinh); // Dinh dang yyyy-MM-dd
            } catch (IllegalArgumentException e) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Ngay sinh phai co dang yyyy-MM-dd, vi du: 2007-12-08");
                return false;
            }
        }
        return true;
    }

    // Them sinh vien
    private void themSinhVien() {
        if (!kiemTraDuLieu()) return;

        String sql = "INSERT INTO SinhVien "
                + "(MaSV, HoTen, NgaySinh, GioiTinh, DiaChi, SoDienThoai) "
                + "VALUES (?, ?, ?, ?, ?, ?)";

        try (Connection conn = layKetNoi();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, jTextField1.getText().trim());
            ps.setString(2, jTextField2.getText().trim());

            if (jTextField3.getText().trim().isEmpty()) {
                ps.setNull(3, java.sql.Types.DATE);
            } else {
                ps.setDate(3, java.sql.Date.valueOf(jTextField3.getText().trim()));
            }

            ps.setString(4, jTextField4.getText().trim());
            ps.setString(5, jTextField5.getText().trim());
            ps.setString(6, jTextField6.getText().trim());

            ps.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(this, "Them sinh vien thanh cong!");
            loadSinhVien();
            lamMoiForm();

        } catch (java.sql.SQLIntegrityConstraintViolationException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ma sinh vien da ton tai hoac du lieu vi pham rang buoc.");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Loi them sinh vien: " + e.getMessage());
        }
    }

    // Sua thong tin sinh vien theo MaSV
    private void suaSinhVien() {
        if (!kiemTraDuLieu()) return;

        String sql = "UPDATE SinhVien SET HoTen=?, NgaySinh=?, GioiTinh=?, "
                   + "DiaChi=?, SoDienThoai=? WHERE MaSV=?";

        try (Connection conn = layKetNoi();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, jTextField2.getText().trim());

            if (jTextField3.getText().trim().isEmpty()) {
                ps.setNull(2, java.sql.Types.DATE);
            } else {
                ps.setDate(2, java.sql.Date.valueOf(jTextField3.getText().trim()));
            }

            ps.setString(3, jTextField4.getText().trim());
            ps.setString(4, jTextField5.getText().trim());
            ps.setString(5, jTextField6.getText().trim());
            ps.setString(6, jTextField1.getText().trim());

            int soDong = ps.executeUpdate();
            if (soDong > 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Cap nhat sinh vien thanh cong!");
                loadSinhVien();
                lamMoiForm();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Khong tim thay ma sinh vien can sua.");
            }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Loi sua sinh vien: " + e.getMessage());
        }
    }

    // Xoa sinh vien theo MaSV
    private void xoaSinhVien() {
        String maSV = jTextField1.getText().trim();
        if (maSV.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Hay nhap Ma sinh vien hoac chon mot dong tren bang de xoa.");
            return;
        }

        int chon = javax.swing.JOptionPane.showConfirmDialog(this,
                "Ban co chac muon xoa sinh vien " + maSV + " khong?",
                "Xac nhan xoa", javax.swing.JOptionPane.YES_NO_OPTION);

        if (chon != javax.swing.JOptionPane.YES_OPTION) return;

        String sql = "DELETE FROM SinhVien WHERE MaSV=?";

        try (Connection conn = layKetNoi();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, maSV);
            int soDong = ps.executeUpdate();

            if (soDong > 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Xoa sinh vien thanh cong!");
                loadSinhVien();
                lamMoiForm();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Khong tim thay sinh vien can xoa.");
            }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Loi xoa sinh vien: " + e.getMessage()
                    + "\nNeu sinh vien da co diem, can xu ly du lieu Diem truoc.");
        }
    }

    // Tim kiem theo MaSV hoac HoTen
    
private void timKiemSinhVien() {
    String tuKhoa = jTextField1.getText().trim();

    if (tuKhoa.isEmpty()) {
        tuKhoa = jTextField2.getText().trim();
    }

    if (tuKhoa.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Vui long nhap ma sinh vien hoac ho ten!");
        return;
    }

    String sql = "SELECT MaSV, HoTen, NgaySinh, GioiTinh, DiaChi, SoDienThoai "
               + "FROM SinhVien WHERE MaSV LIKE ? OR HoTen LIKE ? ORDER BY MaSV";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement ps = conn.prepareStatement(sql)) {

        ps.setString(1, "%" + tuKhoa + "%");
        ps.setString(2, "%" + tuKhoa + "%");

        try (ResultSet rs = ps.executeQuery()) {
            DefaultTableModel model =
                    (DefaultTableModel) tblSinhVien.getModel();

            model.setRowCount(0);

            int dem = 0;

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("MaSV"),
                    rs.getString("HoTen"),
                    rs.getDate("NgaySinh"),
                    rs.getString("GioiTinh"),
                    rs.getString("DiaChi"),
                    rs.getString("SoDienThoai")
                });

                dem++;
            }

            if (dem == 0) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Khong tim thay sinh vien!");
            }
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Loi tim kiem: " + e.getMessage());
    }
}


    // Dua du lieu cua dong dang chon len cac o nhap
    private void hienThiThongTinLenForm() {
        int dong = tblSinhVien.getSelectedRow();
        if (dong < 0) return;

        jTextField1.setText(String.valueOf(tblSinhVien.getValueAt(dong, 0)));
        jTextField2.setText(String.valueOf(tblSinhVien.getValueAt(dong, 1)));

        Object ngaySinh = tblSinhVien.getValueAt(dong, 2);
        jTextField3.setText(ngaySinh == null ? "" : ngaySinh.toString());

        Object gioiTinh = tblSinhVien.getValueAt(dong, 3);
        jTextField4.setText(gioiTinh == null ? "" : gioiTinh.toString());

        Object diaChi = tblSinhVien.getValueAt(dong, 4);
        jTextField5.setText(diaChi == null ? "" : diaChi.toString());

        Object sdt = tblSinhVien.getValueAt(dong, 5);
        jTextField6.setText(sdt == null ? "" : sdt.toString());
    }

